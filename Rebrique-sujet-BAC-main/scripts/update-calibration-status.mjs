import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import { buildCalibrationReport } from "../tests/hard-benchmark/calibration-report.mjs";
import { loadCases } from "../tests/hard-benchmark/import-copy.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const outputPath = join(root, "data", "calibration-status.js");
const casesSource = readFileSync(join(root, "tests", "hard-benchmark", "cases.json"), "utf8");
const auditSource = readFileSync(join(root, "tests", "hard-benchmark", "audit-manifest.json"), "utf8");
const corpusSha256 = createHash("sha256").update(casesSource).update(auditSource).digest("hex");
const report = buildCalibrationReport(loadCases().cases);
const status = {
  corpusSha256,
  copiesCompared: report.copiesCompared,
  activePoles: report.activePoles,
  coveredPoles: report.coveredPoles,
  calibrated: report.calibrated,
  scorePromotionAllowed: report.scorePromotionAllowed,
  promotionBlockers: [...report.promotionBlockers]
};
const prettierConfig = (await prettier.resolveConfig(outputPath)) || {};
const generated = await prettier.format(
  `// Generated by scripts/update-calibration-status.mjs; do not edit manually.\nexport const CALIBRATION_STATUS = Object.freeze(${JSON.stringify(status, null, 2)});\n`,
  { ...prettierConfig, parser: "babel" }
);

if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) {
    console.error("data/calibration-status.js is stale; run npm run calibration:update");
    process.exit(1);
  }
  console.log("Calibration status is current.");
} else {
  writeFileSync(outputPath, generated);
  console.log(`Updated calibration status (${report.copiesCompared} verified copies).`);
}
