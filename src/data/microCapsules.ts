/** Minutes de lecture par domaine. */
export function capsuleMinutesByDomain(): Record<1 | 2 | 3, number> {
  const out = { 1: 0, 2: 0, 3: 0 } as Record<1 | 2 | 3, number>;
  for (const domaine of CAPSULE_DOMAINS) {
    const secondes = MICRO_CAPSULES.filter((c) => domaine.unitIds.includes(c.unitId)).reduce(
      (s, c) => s + c.durationSec,
      0,
    );
    out[domaine.id] = Math.round(secondes / 60);
  }
  return out;
}

