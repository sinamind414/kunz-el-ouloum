// microCapsules.ts — « فكرة في دقيقة » (audit item 15, sprint 11).
//
// Pourquoi ce format
// ------------------
// Deux chaînes de référence prouvent que la micro-capsule n'est pas un gadget :
//   • @Prof_benotmane entretient une playlist entière nommée « فكرة في دقيقة » ;
//   • chez @MostafaBdd, la capsule « كيف نكتب صيغة الحمض الأميني بطريقة صحيحة ؟ »
//     (12:30) fait 151 K vues — PLUS que son cours complet de l'unité 2 (87 K),
//     et « كيف نفرق بين الخلطية و الخلوية ؟ » règle en 2:11 une confusion qui
//     coûte des points chaque année.
// L'app n'avait aucun objet de cette taille : elle proposait des leçons (20-40 min)
// et des flashcards (5 s). Entre les deux, rien. Ce fichier comble ce trou.
//
// Contrat d'écriture d'une capsule (vérifié par microCapsules.lock.test.ts) :
//   1. UNE seule idée. Pas de résumé de leçon.
//   2. Le titre est une QUESTION, celle que l'élève se pose vraiment.
//   3. Elle nomme l'ERREUR qu'elle tue : sans erreur visée, pas de capsule.
//   4. Elle se termine par une auto-évaluation immédiate (question + réponse).
//   5. Durée annoncée honnête : 45 à 120 secondes de lecture.

export interface MicroCapsule {
  /** Identifiant stable. */
  id: string;
  unitId: number;
  /** Le titre EST la question que l'élève se pose. */
  questionAr: string;
  /** Durée de lecture annoncée, en secondes (45-120). */
  durationSec: number;
  /** L'idée unique, 2 à 4 phrases. */
  ideaAr: string;
  /** Le geste mental, en 2 à 4 étapes impératives. */
  stepsAr: string[];
  /** L'erreur précise que la capsule élimine. */
  errorAr: string;
  /** Auto-évaluation immédiate. */
  selfTestAr: string;
  answerAr: string;
  /** Mots-clés de recherche. */
  tags: string[];
  /** Leçon active à ouvrir pour approfondir. */
  lessonId?: string;
}

