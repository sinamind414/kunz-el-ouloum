/** Capsules d'une unité, dans l'ordre éditorial. */
export function capsulesForUnit(unitId: number): MicroCapsule[] {
  return MICRO_CAPSULES.filter((c) => c.unitId === unitId);
}

/** Unités couvertes, triées. */
export function capsuleUnitIds(): number[] {
  return [...new Set(MICRO_CAPSULES.map((c) => c.unitId))].sort((a, b) => a - b);
}

/**
 * Capsule du jour : tirage STABLE sur la journée (même capsule toute la journée,
 * nouvelle le lendemain) — même principe que le drill « مصفاة التعليمات ».
 * `dayKey` au format YYYY-MM-DD ; injecté pour rendre la fonction testable.
 */
export function capsuleOfTheDay(dayKey: string, pool: MicroCapsule[] = MICRO_CAPSULES): MicroCapsule {
  let hash = 0;
  for (let i = 0; i < dayKey.length; i += 1) {
    hash = (hash * 31 + dayKey.charCodeAt(i)) % 100000;
  }
  return pool[hash % pool.length];
}

/** Clé du jour local au format YYYY-MM-DD. */
export function todayKey(now: Date = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${now.getFullYear()}-${p(now.getMonth() + 1)}-${p(now.getDate())}`;
}

