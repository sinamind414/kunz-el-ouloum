// ─── Types ───────────────────────────────────────────────────────────────────

export type MeftahLevelId = 'base' | 'plus' | 'plusplus' | 'bac';

export interface MeftahLevel {
  id: MeftahLevelId;
  order: number;
  title: string;
  subtitle: string;
  fr: string;
  /** Prérequis pédagogique affiché sur la carte d'accueil. */
  prerequisiteAr: string;
  /** Résumé en 10 secondes (bandeau en bas du niveau). */
  tenSecondsAr: string;
  sections: MeftahSection[];
}

export interface MeftahSection {
  id: string;
  /** Pastille numérotée (0، 1، 2، 3، 4، أ، ب ...) telle que sur la carte papier. */
  badge: string;
  title: string;
  introAr?: string;
  /** Étapes clef (chaîne courte — liste à puces). */
  bullets?: string[];
  /** Tableau verbe → mouvement → erreur si présent. */
  table?: MeftahTableRow[];
  /** Rappel verbe canonique lié (methodologyVerbs.tsx) si applicable. */
  linkedVerbId?: string;
  /** Encadré d'alerte rouge (« فاصل إلزامي », pièges...). */
  warnAr?: string;
  /** Encadré doré (règle positive). */
  goldAr?: string;
}

export interface MeftahTableRow {
  verbAr: string;
  moveAr: string;
  mistakeAr: string;
  /** Lien vers un réflexe canonique (METHODOLOGY_VERBS id) si couvert. */
  linkedVerbId?: string;
}

