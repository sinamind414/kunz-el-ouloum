/** Les années couvertes (fondé l'UI : aucune promesse creuse). */
export function anneesCorrigesTypeJury(): number[] {
  return Object.keys(CORRIGES_TYPE_JURY)
    .map(Number)
    .sort((a, b) => a - b);
}

/** Les 3 exercices d'un sujet encodés — vide si l'année n'est pas encodée. */
export function corrigesTypeJuryPour(annee: number, sujet: 1 | 2): CorrigeTypeJuryExercice[] {
  return (CORRIGES_TYPE_JURY[annee] ?? []).filter((c) => c.sujet === sujet);
}
