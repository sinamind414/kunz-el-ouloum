// CE QUE CE REGISTRE EST — ET CE QU'IL N'EST PAS :
//   · il donne, pour chaque exercice, la STRUCTURE OFFICIELLE (barème imprimé
//     sur le sujet : 5/7/8 points) et la liste des CONSIGNES OFFICIELLES ;
//   · pour chaque consigne, « attenduAr » décrit ce qu'un corrigé type de
//     jury demande — contenu tiré de l'énoncé lui-même et du programme
//     officiel tel que l'application l'enseigne (leçons des unités) ;
//   · il NE CONTIENT AUCUN barème par item (aucun chiffre de ventilation
//     n'est imprimé sur le sujet — inventer serait interdit) :
//     → pas de `formes`, donc PAS d'auto-notation : c'est une GRILLE DE
//       JURY (auto-évaluation guidée et correction humaine), PAS un
//       registre noté automatiquement ;
//   · le registre 2025 (`attendusBac2025.ts`, alimenté par le corrigé
//     ministériel) reste la SEULE voie de notation automatique (Pierre 2).
//
// SOURCES ET FIDÉLITÉ (traçabilité) :
//   · énoncés : couche texte des PDF officiels public/bac-sujets/2024/
//     (extraction 2026-10-29) — les consignes sont transcrites mot à mot
//     avec nettoyage du seul bruit de police de la couche texte (fragments
//     latins parasites) ; valeurs de figures NON recopiées (lecture
//     incertaine) : les attendus renvoient aux figures sans les chiffrer ;
//   · thèmes et max confirmed against les photos du sujet officiel relues
//     et documentées (descripteurs « relus sur photos 2026-08-31 ») ;
//   · zéro dialecte — فصحى uniquement (règle permanente).
//
// CONSOMMATEUR : affichage « corrigé type jury » dans BacIdeasView (carte
// par sujet). Extension prévue : branchement au correcteur humain quand les
// années se multiplieront.

