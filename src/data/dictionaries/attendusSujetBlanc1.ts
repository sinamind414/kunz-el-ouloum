import { normalizeAr } from '../../lib/validation/normalizeAr';
import type { AttenduItem, AttendusExercice, ExerciceId } from './attendusBac2025';

let seq = 0;
function item(points: number, formes: string[], texteAr: string, composantes?: string[][]): AttenduItem {
  seq += 1;
  return {
    id: `blanc1-${seq}`,
    texteAr,
    points,
    formes: formes.map((f) => normalizeAr(f).toLowerCase()).filter(Boolean),
    ...(composantes?.length
      ? { composantes: composantes.map((g) => g.map((f) => normalizeAr(f).toLowerCase())) }
      : {}),
    source: 'sujet-blanc-original',
  };
}

